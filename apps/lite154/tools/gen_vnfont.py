"""Generate include/VnFonts.h: anti-aliased (4-bit alpha) Vietnamese fonts for VnText.

Source font: Be Vietnam Pro (SIL OFL, data/BeVietnamPro-*.ttf), drawn for Vietnamese
diacritics. Charset = printable ASCII + every precomposed Vietnamese letter + a few symbols.

Usage: python tools/gen_vnfont.py
"""
import os

from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

VN_LOWER = ('àáảãạăằắẳẵặâầấẩẫậđèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵ')
CHARSET = sorted(set(
    [chr(c) for c in range(0x20, 0x7F)] + list(VN_LOWER) + list(VN_LOWER.upper()) + list('–•°·…‹›±')
))

# (C name, ttf, pixel size)
FONTS = [
    ('VN_FONT_SM', 'BeVietnamPro-SemiBold.ttf', 14),
    ('VN_FONT_MD', 'BeVietnamPro-SemiBold.ttf', 17),
    ('VN_FONT_LG', 'BeVietnamPro-Bold.ttf', 20),
]


def build(name, ttf, size, out):
    font = ImageFont.truetype(os.path.join(ROOT, 'data', ttf), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for ch in CHARSET:
        if ch not in ' ' and font.getmask(ch).getbbox() is None:
            continue  # glyph missing from the ttf
        adv = round(font.getlength(ch))
        mask, (ox, oy) = font.getmask2(ch, mode='L', anchor='ls')
        w, h = mask.size
        bbox = mask.getbbox() if w and h else None
        if bbox is None:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(bitmap)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        px = [mask.getpixel((x0 + x, y0 + y)) for y in range(h) for x in range(w)]
        nib = [(v * 15 + 127) // 255 for v in px]
        if len(nib) % 2:
            nib.append(0)
        off = len(bitmap)
        bitmap += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((ord(ch), w, h, ox + x0, oy + y0, adv, off))

    lo = name.lower()
    out.append(f'// {ttf} {size}px: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes')
    out.append(f'static const uint8_t {lo}_bitmap[] PROGMEM = {{')
    for i in range(0, len(bitmap), 24):
        out.append('  ' + ','.join(f'0x{b:02X}' for b in bitmap[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const VnGlyph {lo}_glyphs[] PROGMEM = {{')
    for code, w, h, xo, yo, adv, off in glyphs:
        out.append(f'  {{0x{code:04X},{w},{h},{xo},{yo},{adv},{off}}},')
    out.append('};')
    out.append(f'static const VnFont {name} = {{{lo}_bitmap, {lo}_glyphs, {len(glyphs)}, '
               f'{ascent + descent}, {ascent}, {descent}}};\n')


def main():
    out = ['#pragma once',
           '// Generated by tools/gen_vnfont.py - do not edit.',
           '#include "VnText.h"', '']
    for args in FONTS:
        build(*args, out)
    with open(os.path.join(ROOT, 'include', 'VnFonts.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote include/VnFonts.h')


if __name__ == '__main__':
    main()
