"""Build src/HanoiAlertsData.cpp from the Pi pipeline's combined_traffic_alerts.csv.

The CSV's ma_loai is already the unified VietHUD type (the pipeline mapped the raw
VietMap/WYN/Papago codes), so it is used as is. The old build_hanoi_db.py re-mapped it a
second time as if it were raw VietMap codes, which scrambled every category
(khu dan cu -> den do, den do -> BOT, BOT -> cam vuot, camera phat nguoi -> dan cu).

VietMap_M1 rows of type 10 carry the real type in toc_do_kmh (1 camera toc do,
2/3 khu dan cu vao/ra, 4 camera phat nguoi, 5 BOT, 6 den do) and sit on the same spot as
an SDCard_WYN row; they are decoded and then merged away by the de-duplication.
Generic "canh bao khac" (type 10) rows have no usable meaning and are dropped.

Usage: python tools/build_alerts_db.py [data/combined_traffic_alerts.csv]
"""
import csv
import math
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'data', 'combined_traffic_alerts.csv')

# Same box as TrafficAlertManager.cpp (Ha Noi + ~200 km)
MIN_LAT, MAX_LAT, MIN_LON, MAX_LON = 19.2, 22.8, 103.9, 107.8

SPEED_CAMERA, RESIDENT, NO_OVERTAKING, CAMERA, TOLL, RED_LIGHT = 1, 2, 3, 4, 5, 6
NAMES = {SPEED_CAMERA: 'camera toc do', RESIDENT: 'khu dan cu', NO_OVERTAKING: 'cam vuot',
         CAMERA: 'camera phat nguoi', TOLL: 'tram BOT', RED_LIGHT: 'den do / camera nga tu'}
VIETMAP_SUBTYPE = {1: SPEED_CAMERA, 2: RESIDENT, 3: RESIDENT, 4: CAMERA, 5: TOLL, 6: RED_LIGHT}

MERGE_M = 30.0      # same type closer than this ...
MERGE_DEG = 35      # ... and facing the same way = one physical point


def heading_diff(a, b):
    d = abs(a - b) % 360
    return 360 - d if d > 180 else d


def load():
    points = []
    with open(CSV_PATH, encoding='utf-8-sig', errors='ignore') as f:
        for r in csv.DictReader(f):
            try:
                lat, lon = float(r['vi_do']), float(r['kinh_do'])
                t = int(r['ma_loai'])
                speed = int(float(r['toc_do_kmh'] or 0))
                heading = int(float(r['huong_do'] or 0)) % 360
            except (KeyError, ValueError):
                continue
            if not (MIN_LAT <= lat <= MAX_LAT and MIN_LON <= lon <= MAX_LON):
                continue
            if t == 10:
                t = VIETMAP_SUBTYPE.get(speed)
                speed = 0
                if t is None:
                    continue
            if t not in NAMES:
                continue
            if t != SPEED_CAMERA or not (20 <= speed <= 130):
                speed = 0
            points.append({'lat': lat, 'lon': lon, 'type': t, 'speed': speed, 'heading': heading})
    return points


def dedupe(points):
    # Prefer rows that know their speed limit and heading, so they survive the merge.
    points.sort(key=lambda p: (p['speed'] == 0, p['heading'] == 0))
    grid = defaultdict(list)
    kept = []
    for p in points:
        gy, gx = int(p['lat'] * 2000), int(p['lon'] * 2000)  # ~55 m cells
        dup = None
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                for q in grid[(gy + dy, gx + dx)]:
                    if q['type'] != p['type']:
                        continue
                    d = math.hypot((q['lat'] - p['lat']) * 111139, (q['lon'] - p['lon']) * 103600)
                    if d > MERGE_M:
                        continue
                    if q['heading'] and p['heading'] and heading_diff(q['heading'], p['heading']) > MERGE_DEG:
                        continue
                    dup = q
                    break
                if dup:
                    break
            if dup:
                break
        if dup:
            if not dup['heading'] and p['heading']:
                dup['heading'] = p['heading']
            continue
        grid[(gy, gx)].append(p)
        kept.append(p)
    return kept


def main():
    raw = load()
    pts = dedupe(raw)
    pts.sort(key=lambda p: (round(p['lat'] * 1e7), round(p['lon'] * 1e7)))
    print(f'{len(raw)} rows in region -> {len(pts)} after merging duplicates')
    for t, n in sorted(Counter(p['type'] for p in pts).items()):
        print(f'  type {t} {NAMES[t]}: {n}')

    with open(os.path.join(ROOT, 'include', 'HanoiAlertsData.h'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('#pragma once\n#include <Arduino.h>\n\n'
                 '// Generated by tools/build_alerts_db.py - do not edit.\n'
                 '#pragma pack(push, 1)\n'
                 'struct HanoiAlertRecord {\n'
                 '    int32_t latE7;\n'
                 '    int32_t lonE7;\n'
                 '    uint16_t heading;   // 0 = unknown\n'
                 '    uint8_t type;       // TrafficAlertType\n'
                 '    uint8_t speed;      // posted limit for ALERT_SPEED_CAMERA, else 0\n'
                 '};\n'
                 '#pragma pack(pop)\n\n'
                 f'#define HANOI_ALERT_COUNT {len(pts)}\n'
                 'extern const HanoiAlertRecord HANOI_ALERTS[] PROGMEM;\n')

    with open(os.path.join(ROOT, 'src', 'HanoiAlertsData.cpp'), 'w', encoding='utf-8', newline='\n') as fc:
        fc.write('#include "HanoiAlertsData.h"\n\n// Generated by tools/build_alerts_db.py - do not edit.\n'
                 'const HanoiAlertRecord HANOI_ALERTS[] PROGMEM = {\n')
        for p in pts:
            fc.write(f"{{{round(p['lat'] * 1e7)},{round(p['lon'] * 1e7)},{p['heading']},{p['type']},{p['speed']}}},\n")
        fc.write('};\n')


if __name__ == '__main__':
    main()
